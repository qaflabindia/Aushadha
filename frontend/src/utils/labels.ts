const CAMEL_KEY = /^[a-z][a-z0-9]*[A-Z][a-zA-Z0-9]*$/;

/** Returns the English label for a UI key; English phrases pass through unchanged. */
export function resolveLabel(key: string): string {
  const label = UI_LABELS[key];
  if (label) {
    return label;
  }
  if (CAMEL_KEY.test(key)) {
    // e.g. "noChunksFound" -> "No chunks found"
    const words = key.replace(/([a-z0-9])([A-Z])/g, '$1 $2').toLowerCase();
    return words.charAt(0).toUpperCase() + words.slice(1);
  }
  return key;
}
